const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..'),THREE=require(path.join(root,'vendor/three.min.js'));
const ctx=vm.createContext({window:{THREE}});vm.runInContext(fs.readFileSync(path.join(root,'src/place-fx.js'),'utf8')+'\nglobalThis.fx=PlaceFX3D;',ctx);
const parent=new THREE.Group(),places=Array.from({length:40},(_,i)=>({i,at:new THREE.Vector3(i%10*.8,.04,Math.floor(i/10)*2),corner:i%10===0}));
const live=ctx.fx.create({parent,places});assert.equal(live.stats().places,40);
const [rings,drops,coins]=parent.children[0].children;
const versions=()=>[rings,drops,coins].map(m=>[m.instanceMatrix.version,m.instanceColor?.version]);
const visibility=()=>[rings,drops,coins].map(m=>m.visible);
const idleVersions=versions();
assert.deepEqual(visibility(),[false,false,false],'unused pools do not submit draw calls');
assert([rings,drops,coins].every(m=>m.count===0));
live.update(0);live.update(1);assert.deepEqual(versions(),idleVersions,'idle pools do not upload instance buffers');
